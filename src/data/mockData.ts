export const getDashboardStats = (universityId?: string): DashboardStats => {
  const filterByUni = (items: LostFoundItem[]) =>
    universityId ? items.filter((i) => i.universityId === universityId) : items;

  const allLost = filterByUni(lostItems);
  const allFound = filterByUni(foundItems);
  const allItems = [...allLost, ...allFound];

  return {
    totalLostItems: allLost.length,
    totalFoundItems: allFound.length,
    pendingVerifications: allItems.filter((i) => i.status === 'pending').length,
    matchedItems: allItems.filter((i) => i.status === 'matched').length,
    returnedItems: allItems.filter((i) => i.status === 'returned').length,
    activeUniversities: universities.filter((u) => u.isActive).length,
  };
};
